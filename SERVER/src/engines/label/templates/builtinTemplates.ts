/**
 * The registry. Order here is the display order in the template picker.
 *
 * A new format is appended to this array and seeded — nothing else changes.
 */
export const BUILTIN_TEMPLATES: readonly BuiltinTemplate[] = [
  defaultClothing,
  smallLabel,
  largeLabel,
  barcodeOnly,
  priceTag,
  saleTag,
  clearanceTag,
  shelfLabel,
  warehouseLabel,
] as const;

/** The template used when a caller does not specify one and no default is set. */
export const FALLBACK_TEMPLATE_CODE = "default-clothing";

export function getBuiltinTemplate(code: string): BuiltinTemplate | undefined {
  return BUILTIN_TEMPLATES.find((template) => template.code === code);
}
