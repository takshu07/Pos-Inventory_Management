// =============================================================================
// BUILT-IN LABEL TEMPLATES
//
// Every template required by the brief, expressed purely as DATA. There is no
// per-template code anywhere in the engine — the same layout pipeline renders
// all of them, and the same pipeline will render templates a user designs in
// the future Custom Label Designer.
//
// Adding a template = appending one object to BUILTIN_TEMPLATES. No existing
// file changes, no renderer changes, no UI changes. That is the "future
// templates should be added without modifying existing code" requirement.
//
// These are seeded into label_templates as isSystem=true rows so they can be
// referenced by foreign key, cloned, and usage-counted — but they are defined
// here in code so a fresh install always has working defaults, and so a
// corrupted row can be re-seeded from a known-good source.
// =============================================================================

